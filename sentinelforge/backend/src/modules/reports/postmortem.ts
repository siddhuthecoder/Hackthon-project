import { HydratedDocument } from 'mongoose';
import { Correlation, IIncident, IncidentComment, ResponseAction, SecurityEvent, Vulnerability } from '../../db/models';
import { escapeHtml as e } from '../integrations/confluence';

function bullets(items: string[] | undefined): string {
  if (!items || items.length === 0) return '<p><em>None recorded.</em></p>';
  return `<ul>${items.map(i => `<li>${e(i)}</li>`).join('')}</ul>`;
}

/** Postmortem body in Confluence storage format, built only from records already in the DB —
 * the same data the incident page and PDF report show. Empty sections say so instead of padding. */
export async function buildPostmortemBody(incident: HydratedDocument<IIncident>): Promise<string> {
  const [correlations, events, actions, comments] = await Promise.all([
    Correlation.find({ incidentId: incident.id }),
    SecurityEvent.find({ _id: { $in: incident.eventIds } }).sort({ timestamp: 1 }).limit(30),
    ResponseAction.find({ incidentId: incident.id }).sort({ createdAt: 1 }),
    IncidentComment.find({ incidentId: incident.id }).sort({ createdAt: 1 }),
  ]);
  const findings = correlations.length
    ? await Vulnerability.find({ _id: { $in: correlations.map(c => c.findingId) }, applicationId: incident.applicationId })
    : [];
  const inv = incident.investigation as
    | { summary?: string; attackPath?: string; impact?: string; recommendedActions?: string[]; uncertainties?: string[]; mode?: string }
    | undefined;

  const parts: string[] = [];
  parts.push(`<h2>Summary</h2><p>${e(inv?.summary ?? `${incident.title} detected by rule ${incident.rule}.`)}</p>`);
  parts.push(
    `<table><tbody>` +
      `<tr><th>Severity</th><td>${e(incident.severity)}</td></tr>` +
      `<tr><th>Status</th><td>${e(incident.status)}</td></tr>` +
      `<tr><th>Detection rule</th><td>${e(incident.rule)}</td></tr>` +
      `<tr><th>Subject</th><td>${e(incident.subject)}</td></tr>` +
      `<tr><th>Source IP</th><td>${e(incident.sourceIp ?? 'unknown')}</td></tr>` +
      `<tr><th>Detected</th><td>${e(incident.detectedAt.toISOString())}</td></tr>` +
      `<tr><th>Owner</th><td>${e(incident.assignedToName ?? 'Unassigned')}</td></tr>` +
      `</tbody></table>`,
  );

  parts.push('<h2>Root cause (correlated vulnerabilities)</h2>');
  if (findings.length === 0) {
    parts.push('<p><em>No previously-known vulnerability was correlated to this incident.</em></p>');
  } else {
    for (const f of findings) {
      const c = correlations.find(x => x.findingId === f.id);
      parts.push(`<p><strong>${e(f.vulnKey)} — ${e(f.title)}</strong> (${e(f.severity)}, ${e(f.cwe ?? '')})<br/>${e(c?.reason ?? '')}</p>`);
      parts.push(`<p>Remediation: ${e(f.remediation)}</p>`);
    }
  }

  parts.push(`<h2>Investigation${inv?.mode ? ` (AI mode: ${e(inv.mode)})` : ''}</h2>`);
  if (inv) {
    parts.push(`<p><strong>Attack path:</strong> ${e(inv.attackPath)}</p><p><strong>Impact:</strong> ${e(inv.impact)}</p>`);
    parts.push('<h3>Open questions</h3>' + bullets(inv.uncertainties));
  } else {
    parts.push('<p><em>No investigation recorded.</em></p>');
  }

  parts.push('<h2>Response actions taken</h2>');
  parts.push(bullets(actions.map(a => `${a.action}${a.target ? ` → ${a.target}` : ''} — ${a.status}${a.approvedBy ? ' (approved)' : ''}`)));

  parts.push('<h2>Follow-ups</h2>' + bullets([...(inv?.recommendedActions ?? []), ...incident.recommendedActions]));

  parts.push('<h2>Timeline (first 30 events)</h2>');
  parts.push(bullets(events.map(ev => `${ev.timestamp.toISOString()} — ${ev.eventType}${ev.endpoint ? ` ${ev.endpoint}` : ''}`)));

  parts.push('<h2>Analyst notes</h2>');
  parts.push(bullets(comments.map(c => `${c.authorName}: ${c.text}`)));

  parts.push('<p><em>Generated by SentinelForge AI from recorded incident data.</em></p>');
  return parts.join('\n');
}
