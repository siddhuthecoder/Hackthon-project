/**
 * Known-correct source patches per vulnerability, used by githubPr.ts to open a real PR.
 *
 * These are deterministic (not AI-generated code) for a reason: the AI (RemediationAgent)
 * already explains root cause, secure approach, and writes the PR description — but having a
 * model generate the literal code patch to a real repo carries real risk of producing broken or
 * subtly-wrong code with nobody to catch it before it's committed. Since CyberLab already ships a
 * hand-written, proven-correct secure implementation for every one of these endpoints (the same
 * logic the lab-fix runtime toggle switches to), the patch here applies that exact same logic as
 * real source code instead of a runtime route rewrite — this is "AI-reviewed, deterministically
 * applied," which is an honest, safer version of the real feature: the PR body is written by the
 * AI from the real evidence, review and merge is still a human decision.
 */
export interface SourcePatch {
  vulnKey: string;
  /** Path relative to the repository root. */
  file: string;
  find: string;
  replace: string;
}

